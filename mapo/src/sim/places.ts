/** (x, z)에서 명소 p 의 꺾은선까지 거리(m) */
export function placeDist(p: Place, x: number, z: number): number {
  const q = p.pts;
  if (q.length === 2) return Math.hypot(x - q[0], z - q[1]);
  let best = Infinity;
  for (let k = 0; k + 3 < q.length; k += 2) {
    const ax = q[k];
    const az = q[k + 1];
    const dx = q[k + 2] - ax;
    const dz = q[k + 3] - az;
    const u = Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / (dx * dx + dz * dz || 1)));
    best = Math.min(best, Math.hypot(ax + dx * u - x, az + dz * u - z));
  }
  return best;
}

/** (x, z)가 든 명소들(비트 k = PLACES[k]). margin 만큼 넓혀 본다 */
export function placeMask(x: number, z: number, margin = 0): number {
  let m = 0;
  PLACES.forEach((p, k) => {
    if (placeDist(p, x, z) < p.r + margin) m |= 1 << k;
  });
  return m;
}

/** 명소 p 가 지금 붐비는 정도 0~1(시각별 붐빔, 날짜는 0시에 바뀐다. 한 시간 사이는 잇는다) */
export function placeLevel(p: Place, now: Now): number {
  const day = (dow: number) => p.prof[dow === 6 ? 2 : dow === 0 ? 3 : dow === 5 ? 1 : 0];
  const h = (((now.tod / 3600) % 24) + 24) % 24;
  const a = Math.floor(h);
  const f = h - a;
  // 23시와 다음 날 0시 사이는 다음 날짜의 0시 값으로 잇는다
  const next = a === 23 ? day((now.dow + 1) % 7)[0] : day(now.dow)[a + 1];
  return (+day(now.dow)[a] * (1 - f) + +next * f) / 9;
}
