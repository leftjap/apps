#!/usr/bin/env node
// 소연 keep export JSON → today_user_* + today_expenses SQL INSERT 추출.
// 사용:
//   node scripts/extract-soyoun-mappings.mjs \
//     --input ~/Downloads/soyoun_app_database.json \
//     --owner-id aeafd9a7-4094-4e7c-a621-188d6b2e336d \
//     > supabase/migrations/0021_import_soyoun.sql

import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((m, a, i, arr) => {
    if (a.startsWith('--')) m.push([a.slice(2), arr[i + 1]]);
    return m;
  }, []),
);
const inputPath = args.input;
const ownerId = args['owner-id'];
if (!inputPath || !ownerId) {
  console.error('usage: --input <path.json> --owner-id <uuid>');
  process.exit(1);
}

const data = JSON.parse(readFileSync(inputPath, 'utf-8'));
const exp = data.gb_expenses || [];

// 다중 카테고리 brand 다수결 결정 (확정 사항 — 사용자 승인)
const BRAND_OVERRIDE = {
  네이버페이: 'fashion',
  모닝글로리: 'culture',
  사러가수퍼마켓: 'dining',
};

// subscribe → etc 변환 (확정 사항)
const CATEGORY_REMAP = { subscribe: 'etc' };

// brand → category 다수결 (BRAND_OVERRIDE 우선)
const brandCatCount = {};
for (const r of exp) {
  if (!r.brand) continue;
  brandCatCount[r.brand] ||= {};
  brandCatCount[r.brand][r.category] = (brandCatCount[r.brand][r.category] || 0) + 1;
}
const brandToCategory = {};
for (const [b, cats] of Object.entries(brandCatCount)) {
  if (BRAND_OVERRIDE[b]) {
    brandToCategory[b] = BRAND_OVERRIDE[b];
    continue;
  }
  brandToCategory[b] = Object.entries(cats).sort((a, c) => c[1] - a[1])[0][0];
}

// merchant → brand 다수결 (brand 가 있는 expense row 만)
const merchBrandCount = {};
for (const r of exp) {
  if (!r.merchant || !r.brand) continue;
  merchBrandCount[r.merchant] ||= {};
  merchBrandCount[r.merchant][r.brand] = (merchBrandCount[r.merchant][r.brand] || 0) + 1;
}
const merchantToBrand = {};
for (const [m, brs] of Object.entries(merchBrandCount)) {
  merchantToBrand[m] = Object.entries(brs).sort((a, c) => c[1] - a[1])[0][0];
}

// SOYOUN_CATEGORIES (코드 expense-classifier.js:25-38 그대로)
const SOYOUN_CATEGORIES = [
  { id: 'dining', name: '외식' },
  { id: 'food', name: '마트' },
  { id: 'convenience', name: '편의점' },
  { id: 'cafe', name: '카페' },
  { id: 'gift', name: '선물' },
  { id: 'cat', name: '고양이' },
  { id: 'health', name: '건강' },
  { id: 'culture', name: '문화' },
  { id: 'fashion', name: '패션' },
  { id: 'overseas', name: '해외체류' },
  { id: 'invest', name: '투자' },
  { id: 'etc', name: '기타' },
];

const sqlEscape = (s) => (s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const sqlInt = (n) => (n == null || Number.isNaN(Number(n)) ? 'NULL' : String(Math.round(Number(n))));

// KST 가정 — date + time → spent_at (+09:00)
const toSpentAt = (date, time) => {
  if (!date) return null;
  const t = time || '00:00';
  return `${date}T${t}:00+09:00`;
};

let out = '';
out += `-- ═══════════════════════════════════════════════════════════════════════════\n`;
out += `-- 0021_import_soyoun.sql — 소연 keep export 데이터 마이그레이션\n`;
out += `-- owner_id: ${ownerId}\n`;
out += `-- generated by: scripts/extract-soyoun-mappings.mjs\n`;
out += `-- ═══════════════════════════════════════════════════════════════════════════\n\n`;

out += `-- 1. SOYOUN picker (12종)\n`;
out += `insert into today_user_categories (user_id, id, name, display_order) values\n`;
out += SOYOUN_CATEGORIES.map((c, i) =>
  `  (${sqlEscape(ownerId)}, ${sqlEscape(c.id)}, ${sqlEscape(c.name)}, ${i})`
).join(',\n');
out += `\non conflict (user_id, id) do nothing;\n\n`;

out += `-- 2. brand → category 매핑 (${Object.keys(brandToCategory).length}종, 다수결)\n`;
out += `insert into today_user_brand_categories (user_id, brand, category_id) values\n`;
out += Object.entries(brandToCategory)
  .map(([b, c]) => `  (${sqlEscape(ownerId)}, ${sqlEscape(b)}, ${sqlEscape(c)})`)
  .join(',\n');
out += `\non conflict (user_id, brand) do nothing;\n\n`;

out += `-- 3. merchant → brand 정규화 (${Object.keys(merchantToBrand).length}종, 다수결)\n`;
out += `insert into today_user_merchant_aliases (user_id, merchant_pattern, brand) values\n`;
out += Object.entries(merchantToBrand)
  .map(([m, b]) => `  (${sqlEscape(ownerId)}, ${sqlEscape(m)}, ${sqlEscape(b)})`)
  .join(',\n');
out += `\non conflict (user_id, merchant_pattern) do nothing;\n\n`;

out += `-- 4. expense rows (${exp.length}건). subscribe 2건 → etc 변환.\n`;
out += `--    id 신규 uuid, 원본 keep id 는 meta.keep_id 보관. spent_at KST(+09:00) 가정.\n`;
out += `insert into today_expenses (id, owner_id, spent_at, amount_krw, merchant_raw, merchant, brand, category, card, memo, source, created_at, meta) values\n`;
out += exp
  .map((r) => {
    const cat = CATEGORY_REMAP[r.category] || r.category || 'etc';
    const spentAt = toSpentAt(r.date, r.time);
    const meta = JSON.stringify({ keep_id: r.id, keep_source: r.source });
    return `  (${sqlEscape(randomUUID())}, ${sqlEscape(ownerId)}, ${sqlEscape(spentAt)}, ${sqlInt(r.amount)}, ${sqlEscape(r.merchant)}, ${sqlEscape(r.merchant)}, ${sqlEscape(r.brand)}, ${sqlEscape(cat)}, ${sqlEscape(r.card)}, ${sqlEscape(r.memo || '')}, ${sqlEscape(r.source || 'import')}, ${sqlEscape(r.created)}, ${sqlEscape(meta)}::jsonb)`;
  })
  .join(',\n');
out += `\non conflict (owner_id, sms_raw, spent_at) do nothing;\n`;

process.stdout.write(out);

const summary = {
  totalRows: exp.length,
  brandMappings: Object.keys(brandToCategory).length,
  merchantAliases: Object.keys(merchantToBrand).length,
  pickerCategories: SOYOUN_CATEGORIES.length,
  categoryDist: exp.reduce((m, r) => {
    const c = CATEGORY_REMAP[r.category] || r.category || '(null)';
    m[c] = (m[c] || 0) + 1;
    return m;
  }, {}),
};
console.error('=== summary ===');
console.error(JSON.stringify(summary, null, 2));
