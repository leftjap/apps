#!/usr/bin/env node
// expense-classifier.js 의 LEFTJAP_CATEGORIES / BRAND_CATEGORY_MAP / MERCHANT_TO_BRAND
// freeze 객체를 leftjap owner_id 기준 SQL INSERT 로 변환.
// 사용:
//   node scripts/extract-leftjap-mappings.mjs \
//     --owner-id 7bae5645-61c6-4476-9ff2-4c30a72812ff \
//     > supabase/migrations/0020_seed_leftjap.sql

import { LEFTJAP_CATEGORIES, BRAND_CATEGORY_MAP, MERCHANT_TO_BRAND } from '../src/services/expense-classifier.js';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((m, a, i, arr) => {
    if (a.startsWith('--')) m.push([a.slice(2), arr[i + 1]]);
    return m;
  }, []),
);
const ownerId = args['owner-id'];
if (!ownerId) {
  console.error('usage: --owner-id <uuid>');
  process.exit(1);
}

const sqlEscape = (s) => (s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);

let out = '';
out += `-- ═══════════════════════════════════════════════════════════════════════════\n`;
out += `-- 0020_seed_leftjap.sql — leftjap default 매핑 seed\n`;
out += `-- owner_id: ${ownerId}\n`;
out += `-- generated by: scripts/extract-leftjap-mappings.mjs (from expense-classifier.js freeze)\n`;
out += `-- ═══════════════════════════════════════════════════════════════════════════\n\n`;

out += `-- 1. LEFTJAP picker (${LEFTJAP_CATEGORIES.length}종)\n`;
out += `insert into today_user_categories (user_id, id, name, display_order) values\n`;
out += LEFTJAP_CATEGORIES.map((c, i) =>
  `  (${sqlEscape(ownerId)}, ${sqlEscape(c.id)}, ${sqlEscape(c.name)}, ${i})`
).join(',\n');
out += `\non conflict (user_id, id) do nothing;\n\n`;

out += `-- 2. brand → category 매핑 (${Object.keys(BRAND_CATEGORY_MAP).length}종)\n`;
out += `insert into today_user_brand_categories (user_id, brand, category_id) values\n`;
out += Object.entries(BRAND_CATEGORY_MAP)
  .map(([b, c]) => `  (${sqlEscape(ownerId)}, ${sqlEscape(b)}, ${sqlEscape(c)})`)
  .join(',\n');
out += `\non conflict (user_id, brand) do nothing;\n\n`;

out += `-- 3. merchant → brand 정규화 (${Object.keys(MERCHANT_TO_BRAND).length}종)\n`;
out += `insert into today_user_merchant_aliases (user_id, merchant_pattern, brand) values\n`;
out += Object.entries(MERCHANT_TO_BRAND)
  .map(([m, b]) => `  (${sqlEscape(ownerId)}, ${sqlEscape(m)}, ${sqlEscape(b)})`)
  .join(',\n');
out += `\non conflict (user_id, merchant_pattern) do nothing;\n`;

process.stdout.write(out);

console.error(`=== summary === picker=${LEFTJAP_CATEGORIES.length} brand=${Object.keys(BRAND_CATEGORY_MAP).length} merchant=${Object.keys(MERCHANT_TO_BRAND).length}`);
